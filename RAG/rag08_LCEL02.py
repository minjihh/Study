model = ChatOpenAI(
    model_name = 'gpt-5.6-terra',
    temperature = 0,
    api_key = api_key,
    base_url= base_url,
)

# | -> or 연산자
# 아래 구문으로 override
chain = prompt | model

input = {"topic" : "3DGS와 NeRF 차이점", "how": "초등학생도 이해하기 쉽게"}

# invoke가 model.predict과 같은 기능
response = chain.invoke(input)
print(response.content)


